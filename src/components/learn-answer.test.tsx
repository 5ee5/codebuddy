import { isValidElement, type ReactElement, type ReactNode } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { describe, expect, it } from "vitest";
import { answerMeta, LearnAnswer } from "@/components/learn-answer";
import { CopyButton } from "@/components/ui/copy-button";
import type { AssistantAnswer, LearnRequest } from "@/lib/assistant/types";
import { accessibleText, innerTextOf } from "@/test/markup";

const ISO = "2026-10-24T18:43:26.000Z";
const fixedTime = () => "9:43:26 PM";

const CODE = 'name = "Sam"\nage = 10\n\nprint(name)\nprint(age)\n\nif age > 9:\n    print("double digits")\n';

const answer: AssistantAnswer<LearnRequest> = {
  status: "answered",
  mode: "learn",
  model: "claude-sonnet-5-5",
  createdAt: ISO,
  response: {
    mode: "learn",
    explanation: "A variable stores a value.",
    example: { language: "python", code: CODE },
    keyPoints: ["Names point at values."],
    followUpQuestions: [],
  },
};

/** The rendered provenance paragraph, as plain text a reader would get. */
function metaText(a: AssistantAnswer<LearnRequest>): string {
  const html = renderToStaticMarkup(<LearnAnswer answer={a} />);
  const p = html.match(/<p class="font-mono text-xs text-mode">[\s\S]*?<\/p>/)![0];
  return accessibleText(p).replace(/\s+/g, " ").trim();
}

describe("answerMeta", () => {
  it("returns provider, model and time in order", () => {
    expect(answerMeta(answer, fixedTime)).toEqual([
      { key: "provider", text: "Generated by Claude" },
      { key: "model", text: "claude-sonnet-5-5" },
      { key: "time", text: "9:43:26 PM", dateTime: ISO },
    ]);
  });

  it("uses the browser's own time format by default", () => {
    // Same process, same locale and timezone: independent of where tests run.
    expect(answerMeta(answer).at(-1)!.text).toBe(new Date(ISO).toLocaleTimeString());
  });

  it.each([
    ["an empty model", { model: "", createdAt: ISO }, ["provider", "time"]],
    ["a blank model", { model: "   ", createdAt: ISO }, ["provider", "time"]],
    ["a missing timestamp", { model: "m" }, ["provider", "model"]],
    ["an invalid timestamp", { model: "m", createdAt: "not a date" }, ["provider", "model"]],
    ["nothing optional", {}, ["provider"]],
  ])("skips %s", (_label, input, keys) => {
    expect(answerMeta(input, fixedTime).map((part) => part.key)).toEqual(keys);
  });
});

describe("LearnAnswer metadata", () => {
  const time = new Date(ISO).toLocaleTimeString();

  it("reads with clear separators", () => {
    // The "·" is decorative (aria-hidden); the words stay apart through real spaces.
    expect(metaText(answer)).toBe(`Generated by Claude claude-sonnet-5-5 ${time}`);
    const html = renderToStaticMarkup(<LearnAnswer answer={answer} />);
    const visible = html.match(/<p class="font-mono text-xs text-mode">[\s\S]*?<\/p>/)![0];
    const shown = visible.replace(/<svg[\s\S]*?<\/svg>/, "").replace(/<[^>]+>/g, "");
    expect(shown).toBe(`Generated by Claude · claude-sonnet-5-5 · ${time}`);
    expect(visible).toContain(`<time dateTime="${ISO}"`);
  });

  it("has no doubled or dangling separators when values are missing", () => {
    for (const partial of [{ model: "" }, { createdAt: "invalid" }, { model: "", createdAt: "" }]) {
      const html = renderToStaticMarkup(<LearnAnswer answer={{ ...answer, ...partial }} />);
      const shown = html
        .match(/<p class="font-mono text-xs text-mode">[\s\S]*?<\/p>/)![0]
        .replace(/<svg[\s\S]*?<\/svg>/, "")
        .replace(/<[^>]+>/g, "");
      expect(shown).not.toMatch(/·\s*·/);
      expect(shown.trim()).not.toMatch(/^·|·$/);
      expect(shown).toContain("Generated by Claude");
    }
  });
});

/** Every element in a not-yet-rendered tree, including ones passed as props. */
function elements(node: ReactNode): ReactElement[] {
  if (Array.isArray(node)) return node.flatMap(elements);
  if (!isValidElement(node)) return [];
  const props = node.props as Record<string, unknown>;
  return [node, ...Object.values(props).flatMap((value) => elements(value as ReactNode))];
}

describe("LearnAnswer code example", () => {
  it("shows the example code exactly", () => {
    const html = renderToStaticMarkup(<LearnAnswer answer={answer} />);
    expect(innerTextOf(html, "code")).toBe(CODE);
  });

  it("copies exactly the original code, not labels or the file name", () => {
    const tree = LearnAnswer({ answer });
    const copyButtons = elements(tree).filter((el) => el.type === CopyButton);
    expect(copyButtons).toHaveLength(1);
    expect((copyButtons[0].props as { text: string }).text).toBe(CODE);
  });
});
