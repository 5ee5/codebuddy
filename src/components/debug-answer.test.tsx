import { isValidElement, type ReactElement, type ReactNode } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { describe, expect, it } from "vitest";
import { DebugAnswer } from "@/components/debug-answer";
import { CopyButton } from "@/components/ui/copy-button";
import type { AssistantAnswer, DebugRequest, DebugResponse } from "@/lib/assistant/types";
import { accessibleText, innerTextOf } from "@/test/markup";

const FIXED = 'numbers = [10, 20, 30]\n\nfor i in range(len(numbers)):\n\tif numbers[i] > 0:\n        print(f"<{numbers[i]}>")\n';

const diagnosed: DebugResponse = {
  mode: "debug",
  outcome: "diagnosed",
  diagnosis: "The loop reads one position past the end of the list.",
  explanation: "range(4) gives 0, 1, 2 and 3.\n\nThe list only has positions 0, 1 and 2.",
  confirmed: ["The list has three items."],
  hypotheses: ["The 4 may have been copied from an older list."],
  missingInfo: [],
  correctedCode: { language: "python", code: FIXED },
  changes: [{ change: "range(4) became range(len(numbers))", reason: "It follows the list length." }],
  nextSteps: ["Run it and check that it prints three numbers."],
};

const needsMoreInfo: DebugResponse = {
  mode: "debug",
  outcome: "needs_more_info",
  diagnosis: "The code alone doesn't show why the total is wrong.",
  explanation: "The loop looks correct.",
  confirmed: [],
  hypotheses: ["The numbers might be read as text."],
  missingInfo: ["The exact input you typed."],
  changes: [],
  nextSteps: ["Print each value before adding it."],
};

function answer(response: DebugResponse): AssistantAnswer<DebugRequest> {
  return { status: "answered", mode: "debug", model: "claude-sonnet-5-5", createdAt: "2026-10-24T18:43:26.000Z", response };
}

const headings = (html: string) => [...html.matchAll(/<h3[^>]*>([^<]+)<\/h3>/g)].map((m) => m[1]);

/** Every element in a not-yet-rendered tree, including ones passed as props. */
function elements(node: ReactNode): ReactElement[] {
  if (Array.isArray(node)) return node.flatMap(elements);
  if (!isValidElement(node)) return [];
  const props = node.props as Record<string, unknown>;
  return [node, ...Object.values(props).flatMap((value) => elements(value as ReactNode))];
}

describe("DebugAnswer (diagnosed)", () => {
  const html = renderToStaticMarkup(<DebugAnswer answer={answer(diagnosed)} />);

  it("shows every section in order", () => {
    expect(headings(html)).toEqual([
      "Likely problem",
      "Explanation",
      "What’s certain",
      "Possible causes (not confirmed)",
      "Corrected code",
      "Changes explained",
      "Next steps",
    ]);
  });

  it("says plainly that the code was not run or tested", () => {
    expect(accessibleText(html)).toContain("did not run or test it");
    expect(accessibleText(html)).not.toMatch(/\b(I ran|was executed|tests pass)/i);
  });

  it("keeps confirmed facts and unconfirmed causes apart", () => {
    const text = accessibleText(html);
    const certain = text.indexOf("The list has three items.");
    const possible = text.indexOf("The 4 may have been copied");
    expect(text.indexOf("What’s certain")).toBeLessThan(certain);
    expect(text.indexOf("Possible causes (not confirmed)")).toBeLessThan(possible);
    expect(certain).toBeLessThan(text.indexOf("Possible causes"));
  });

  it("renders the corrected code exactly, with indentation and blank lines", () => {
    expect(innerTextOf(html, "code")).toBe(FIXED);
  });

  it("copies exactly the corrected code", () => {
    const copy = elements(DebugAnswer({ answer: answer(diagnosed) })).filter((el) => el.type === CopyButton);
    expect(copy).toHaveLength(1);
    expect((copy[0].props as { text: string }).text).toBe(FIXED);
  });

  it("explains each change with its reason", () => {
    expect(accessibleText(html)).toMatch(/range\(4\) became range\(len\(numbers\)\)\s*Why: It follows the list length\./);
  });

  it("shows the provenance line with model and time", () => {
    expect(accessibleText(html)).toContain("Generated by Claude");
    expect(html).toContain("claude-sonnet-5-5");
    expect(html).toContain('<time dateTime="2026-10-24T18:43:26.000Z"');
  });
});

describe("DebugAnswer (needs more information)", () => {
  const html = renderToStaticMarkup(<DebugAnswer answer={answer(needsMoreInfo)} />);

  it("asks for the missing information and offers no corrected code", () => {
    const text = accessibleText(html);
    expect(text).toContain("More information needed");
    expect(text).toContain("The exact input you typed.");
    expect(headings(html)).not.toContain("Corrected code");
    expect(headings(html)).not.toContain("Changes explained");
    expect(html).not.toContain("<code");
  });

  it("labels the diagnosis as incomplete and still gives next steps", () => {
    expect(headings(html)).toEqual([
      "Not enough information yet",
      "Explanation",
      "Possible causes (not confirmed)",
      "Next steps",
    ]);
  });
});

describe("DebugAnswer optional sections", () => {
  it("omits empty lists and the code section when there is no fix", () => {
    const html = renderToStaticMarkup(
      <DebugAnswer
        answer={answer({ ...diagnosed, confirmed: [], hypotheses: [], correctedCode: undefined, changes: [] })}
      />,
    );
    expect(headings(html)).toEqual(["Likely problem", "Explanation", "Next steps"]);
  });
});
