import { Fragment, type ReactNode } from "react";
import { Icon } from "@/components/icons";
import { CodeBlock } from "@/components/ui/code-block";
import { CopyButton } from "@/components/ui/copy-button";
import { eyebrow } from "@/components/ui/styles";
import type { AssistantAnswer, LearnRequest } from "@/lib/assistant/types";
import { LANGUAGE_EXTENSIONS, LANGUAGE_LABELS } from "@/lib/languages";

/**
 * Renders inline `code` spans inside plain model text. Everything is passed
 * to React as text, so model output can never inject HTML.
 */
function RichText({ text }: { text: string }) {
  return text.split(/(`[^`\n]+`)/).map((part, i) =>
    part.length > 2 && part.startsWith("`") && part.endsWith("`") ? (
      <code key={i} className="rounded-sm bg-code px-1 py-0.5 font-mono text-[0.9em]">
        {part.slice(1, -1)}
      </code>
    ) : (
      part
    ),
  );
}

function Section({ title, children }: { title: string; children: ReactNode }) {
  return (
    <section className="flex flex-col gap-2.5">
      <h3 className={eyebrow}>{title}</h3>
      {children}
    </section>
  );
}

export interface MetaPart {
  key: "provider" | "model" | "time";
  text: string;
  /** Set on the time part: the original ISO timestamp for `<time dateTime>`. */
  dateTime?: string;
}

/**
 * The provenance line's parts, in order. A blank model or a missing or
 * invalid timestamp is left out, so no separator is ever doubled or dangling.
 */
export function answerMeta(
  { model, createdAt }: { model?: string; createdAt?: string },
  formatTime: (date: Date) => string = (date) => date.toLocaleTimeString(),
): MetaPart[] {
  const parts: MetaPart[] = [{ key: "provider", text: "Generated by Claude" }];
  if (model?.trim()) parts.push({ key: "model", text: model.trim() });
  const date = createdAt ? new Date(createdAt) : null;
  if (date && !Number.isNaN(date.getTime())) {
    parts.push({ key: "time", text: formatTime(date), dateTime: createdAt });
  }
  return parts;
}

/** A validated Learn answer from the AI, with its provenance stated up front. */
export function LearnAnswer({ answer }: { answer: AssistantAnswer<LearnRequest> }) {
  const { response } = answer;
  const paragraphs = response.explanation.split(/\n\s*\n/).filter((p) => p.trim());
  const meta = answerMeta(answer);

  return (
    <div className="flex flex-col gap-6">
      <div className="border-l-2 border-mode bg-mode-soft px-4 py-3 text-sm leading-relaxed">
        {/* Inline text with real spaces, so the parts stay apart when read or copied. */}
        <p className="font-mono text-xs text-mode">
          <Icon name="sparkles" className="mr-1.5 inline size-3.5 align-[-0.2em]" />
          {meta.map((part, i) => (
            <Fragment key={part.key}>
              {i > 0 && (
                <>
                  {" "}
                  <span aria-hidden="true">·</span>{" "}
                </>
              )}
              {part.dateTime ? (
                <time dateTime={part.dateTime} className="whitespace-nowrap">
                  {part.text}
                </time>
              ) : (
                <span className="whitespace-nowrap">{part.text}</span>
              )}
            </Fragment>
          ))}
        </p>
        <p className="mt-1 text-muted">
          AI can make mistakes. Run the example yourself and check anything that seems off.
        </p>
      </div>

      <Section title="Explanation">
        <div className="flex flex-col gap-3 leading-relaxed">
          {paragraphs.map((p, i) => (
            <p key={i} className="whitespace-pre-line">
              <RichText text={p} />
            </p>
          ))}
        </div>
      </Section>

      {response.example && (
        <Section title="Code example">
          <CodeBlock
            title={`example.${LANGUAGE_EXTENSIONS[response.example.language]}`}
            language={LANGUAGE_LABELS[response.example.language]}
            label="Code example"
            code={response.example.code}
            actions={<CopyButton text={response.example.code} what="Code example" />}
          />
        </Section>
      )}

      <Section title="Key points">
        <ul className="flex flex-col gap-2 text-sm leading-relaxed">
          {response.keyPoints.map((point, i) => (
            <li key={i} className="flex gap-2.5">
              <Icon name="check" className="mt-0.5 size-4 shrink-0 text-mode" />
              <span>
                <RichText text={point} />
              </span>
            </li>
          ))}
        </ul>
      </Section>

      {response.followUpQuestions.length > 0 && (
        <Section title="Follow-up questions">
          <ul className="divide-y divide-line border-y border-line text-sm">
            {response.followUpQuestions.map((question, i) => (
              <li key={i} className="flex gap-2 py-2.5">
                <span aria-hidden="true" className="font-mono text-mode">
                  ›
                </span>
                <span>
                  <RichText text={question} />
                </span>
              </li>
            ))}
          </ul>
        </Section>
      )}
    </div>
  );
}
